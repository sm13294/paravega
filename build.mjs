// Library bundles (ESM for browsers, CJS for Node tests). The worker is
// ParaWeb's resident worker (src/resident), shipped as a function string.
import * as esbuild from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = p => path.join(here, "src", p);

// Vega library code for kernels, as a source string run once in every worker:
// one built from Vega 6's packages and one from Vega 5.33's (installed as vega5,
// with its own vega-scale, vega-scenegraph and vega-time), so that scales, symbol
// bounds and time units in the workers are those of the Vega that runs the view.
{
  const fs = await import("node:fs");
  const v5 = p => path.join(here, "node_modules/vega5/node_modules", p);
  const lib = async alias => (await esbuild.build({
    entryPoints: [src("runtime/workerlib.ts")], bundle: true, write: false, format: "iife", platform: "browser",
    globalName: "__pwlib", target: "es2020", minify: true, alias,
  })).outputFiles[0].text;
  const v6 = await lib({});
  const v5lib = fs.existsSync(v5("vega-scenegraph"))
    ? await lib({ "vega-scale": v5("vega-scale"), "vega-scenegraph": v5("vega-scenegraph"), "vega-time": v5("vega-time") })
    : v6;
  fs.writeFileSync(src("runtime/workerlib.generated.ts"),
    "// Generated by build.mjs from workerlib.ts; do not edit.\n" +
    "export const WORKER_LIBRARY = " + JSON.stringify(v6) + ";\n" +
    "/** The same library built from Vega 5.33's packages. */\n" +
    "export const WORKER_LIBRARY_V5 = " + JSON.stringify(v5lib) + ";\n");
}

const common = {
  entryPoints: [src("index.ts")],
  bundle: true,
  target: "es2020",
  sourcemap: true,
  logOverride: { "direct-eval": "silent" },
  // ParaWeb's GPU context loads the Dawn-based "webgpu" package only in
  // Node.js when navigator.gpu is missing; never bundle it.
  external: ["webgpu"],
};

await esbuild.build({ ...common, format: "esm", platform: "browser", outfile: path.join(here, "dist/paraweb-vega.mjs") });
await esbuild.build({ ...common, format: "cjs", platform: "node", outfile: path.join(here, "dist/paraweb-vega.cjs") });
console.log("built paraweb-vega");

// Baseline: Mosaic + DuckDB-WASM adapter used by the benchmark page.
await esbuild.build({
  entryPoints: [path.join(here, "demo/mosaic-entry.js")],
  bundle: true, format: "esm", platform: "browser", target: "es2022",
  outfile: path.join(here, "demo/mosaic-bundle.js"), logLevel: "warning",
});
console.log("built demo/mosaic-bundle.js");

// Baseline: Falcon (falcon-vis) adapter, bundled against falcon-vis's own
// copies of Apache Arrow and DuckDB-WASM.
const falconDeps = path.join(here, "node_modules/falcon-vis/node_modules");
await esbuild.build({
  entryPoints: [path.join(here, "demo/falcon-entry.js")],
  bundle: true, format: "esm", platform: "browser", target: "es2022",
  outfile: path.join(here, "demo/falcon-bundle.js"), logLevel: "warning",
  alias: {
    "apache-arrow": path.join(falconDeps, "apache-arrow/Arrow.dom.mjs"),
    "@duckdb/duckdb-wasm": path.join(falconDeps, "@duckdb/duckdb-wasm/dist/duckdb-browser.mjs"),
  },
});
console.log("built demo/falcon-bundle.js");
